//! Builds the vendored libtexprintf, the C library behind `utftex`.
//!
//! The source is vendored in `vendor/libtexprintf` and pinned to tag `v.1.31`
//! (commit `18977837b20649d56a651eb6bf846f1c914db77a`), GPL-3.0-only; see
//! `vendor/libtexprintf/COPYING`. Nothing is fetched at build time.
//!
//! Upstream builds two generated headers with shell scripts, `errorflags.h`
//! and `errormessages.h`, which are not checked in. Rather than shell out to
//! `egrep`/`awk`, this script does the same scan in Rust: every
//! `// ERRORFLAG NAME "message"` comment, in the order the upstream script
//! visits the files, becomes `#define NAME <n>` and an entry in
//! `EMessages[]`, with the index being the line number in that collection.
//! `error.c` sizes its flag array from the `NERR` macro this writes.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The files `src/Makefile.am` compiles into `libtexprintf`, in its order.
const SOURCES: &[&str] = &[
    "boxes.c",
    "drawbox.c",
    "texprintf.c",
    "parser.c",
    "lexer.c",
    "error.c",
    "stringutils.c",
];

/// The files `gen_errorflags.sh` scans for `// ERRORFLAG` comments, in its
/// order — which is the order the indices in `errorflags.h` follow.
const ERROR_SOURCES: &[&str] = &["boxes.c", "drawbox.c", "lexer.c", "parser.c"];

fn main() {
    let vendor = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("vendor/libtexprintf");
    let src = vendor.join("src");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));

    generate_error_headers(&src, &out);

    let mut build = cc::Build::new();
    build
        .include(&src)
        .include(&out)
        // Vendored code: its warnings are not ours to fix, and one of them
        // (`texstring` handing a `const char *` to `ParseString`) is a false
        // positive — the input is a mutable copy made by our wrapper.
        .flag_if_supported("-Wno-discarded-qualifiers")
        .warnings(false);
    for source in SOURCES {
        build.file(src.join(source));
        println!("cargo:rerun-if-changed={}", src.join(source).display());
    }
    build.compile("texprintf");

    // `lexer.c` calls `roundf`. On MSVC it lives in the CRT, which Rust
    // already links, so only the other targets need the maths library.
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() != Ok("msvc") {
        println!("cargo:rustc-link-lib=m");
    }

    for name in ["COPYING", "README.md"] {
        println!("cargo:rerun-if-changed={}", vendor.join(name).display());
    }
    println!("cargo:rerun-if-changed={}", src.display());
}

/// Writes the two headers `error.c` includes, as `gen_errorflags.sh` would.
fn generate_error_headers(src: &Path, out: &Path) {
    let mut flags = String::from("/* File generated by build.rs, do not edit by hand */\n");
    let mut messages = String::from(
        "/* File generated by build.rs, do not edit by hand */\nchar *EMessages[] = {\n",
    );

    let mut count = 0;
    for source in ERROR_SOURCES {
        let path = src.join(source);
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("reading {}: {error}", path.display()));
        for line in text.lines() {
            let Some(comment) = line.find("// ERRORFLAG") else {
                continue;
            };
            let rest = line[comment + "// ERRORFLAG".len()..].trim_start();
            let mut parts = rest.splitn(2, char::is_whitespace);
            let name = parts.next().unwrap_or_default();
            let message = parts.next().unwrap_or_default().trim();
            // Upstream takes the first quoted run as the message. A flag
            // without one would break the array, so it is a build error here
            // rather than a silent mismatch with the C sources.
            let Some(start) = message.find('"') else {
                panic!("{source}: ERRORFLAG {name} has no message");
            };
            let Some(end) = message[start + 1..].find('"') else {
                panic!("{source}: ERRORFLAG {name} has an unterminated message");
            };
            let message = &message[start + 1..start + 1 + end];
            writeln!(flags, "#define {name} {count}").expect("writing to a String");
            writeln!(messages, "\t\"{message}\",").expect("writing to a String");
            count += 1;
        }
    }
    writeln!(flags, "#define NERR {count}").expect("writing to a String");
    messages.push_str("\tNULL\n};\n");

    for (name, contents) in [("errorflags.h", flags), ("errormessages.h", messages)] {
        let path = out.join(name);
        std::fs::write(&path, contents)
            .unwrap_or_else(|error| panic!("writing {}: {error}", path.display()));
    }
}
